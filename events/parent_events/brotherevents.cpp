void BrotherEvents::watch_tv()
{
    if(root->getHour() == 23 && root->vEvent(brother_tv_enable) == 0 && root->vEvent(family_trip) == 0)
        go_away();
    else
        root->watch_tv_on_sofa();
}

void BrotherEvents::go_away()
{
    root->rendNpcProfile(brother);
    root->setText(str(1));
    makeActBtn("korrParr",act(0));
    makeActBtn("sendBrother",act(1));
}

void BrotherEvents::brother_help_qw()
{
    if(root->vQuest(qwBrotherHelp) == 2)
        brother_help_qw2();
    else
    {
        root->rendVideoPage(this);
        root->vQuest(qwBrotherHelpDay) = root->getDay();
        root->setVideo(media(4),960,540);
        root->setText(str(10));
        makeActBtn("BHQgoaway",act(6));
        makeActBtn("BHQstop",act(7));
    }
}

void BrotherEvents::brother_help_qw2()
{
    root->rendVideoPage(this);
    root->vQuest(qwBrotherHelpDay) = root->getDay();
    root->setVideo(media(4),960,540);
    root->setText(str(15));
    if(root->vSkill(domination) < -10)
        root->addText(str(16));
    else
        root->addText(str(15));
    makeActBtn("BHQ2",act(5));
}

