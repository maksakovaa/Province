void BrotherEvents::makeActBtn(QString action, QString actName)
{
    QActButton* btn = new QActButton(action,"BrotherEvents");
    btn->setText(actName);
    connect(btn, &QActButton::sigAct, this, &BrotherEvents::actionHandler);
    root->addActions(btn);
}

