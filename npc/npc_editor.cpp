int NPC_Editor::getAvgRelation(npcGroup group)
{
    int rel_summ = 0;
    int rel_count = 0;
    for (int i = 0; i < 52; ++i)
    {
        if(npcs[i].group == group)
        {
            rel_count++;
            rel_summ += npcs[i].relation;
        }
    }
    if(rel_count > 0)
        return rel_summ / rel_count;
    else
        return 0;
}

