void NPC_Editor::changeRep(char act, int id, int val, int cup, bool msgShow)
{
    // повышение/понижение отношений + уведомление
    // ремейк функции @wannabee
    // gs 'npc_editor','change_rep','ЧтоДелаем', НомерНПС, НаСколькоИзменяем, ПределРоста, СкрытьСообщения
    // ЧтоДелаем: повышаем, понижаем или ничего не делаем, но выводим сообщение
    // НаСколькоИзменяем - если надо изменить отношения не по формуле, а на определенное число
    // ПределРоста - максимальное значение, до которого стоит повышать/понижать отношения
    // СкрытьСообщения - 0/1, по умолчанию сообщение не скрывается (0)
    if(id == 0)
        return;
    if(npcs[id].know == false)
        npcs[id].know = true;
    int changeVal = 0;
    if(act == '+')
    {
        if(val == 0)
        {
            if(gVStatus(vnesh) < 40) changeVal += 1;
            else changeVal += (gVStatus(vnesh) - 30) / 10;
            if(gVSKill(intellect) < 50) changeVal += 1;
            else changeVal += gVSKill(intellect)/25;
            if(gVStatus(nerdism) > 0)
            {
                if(gVStatus(nerdism) < 20) changeVal -= 1;
                else changeVal -= 2;
            }
        }
        if(cup > 0)
        {
            if(changeVal - npcs[id].relation < 0)
                npcs[id].relation += changeVal;
            else
            {
                npcs[id].relation += changeVal;
                if(npcs[id].relation > cup)
                    npcs[id].relation = cup;
            }
        }
        else
            npcs[id].relation += changeVal;
        if(npcs[id].relation > 100)
            npcs[id].relation = 100;
        if(msgShow == true && changeVal != 0)
        {
            if(npcs[id].relation == 100)
                message("max");
            else
                message("up");
        }
        else
            message("neutral");
    }
    else if(act == '-')
    {
        if(val == 0)
            changeVal = npcs[id].relation / 10;
        npcs[id].relation -= changeVal;
        if(npcs[id].relation < 0)
            npcs[id].relation = 0;
        if(changeVal != 0 && msgShow == true)
            message("down");
        else
            message("neutral");
    }
    else
        if(msgShow == true)
            message("neutral");
}

